function clean(name) {
  return name
    .replace(/card/g, 'slab')
    .replace(/tile/g, 'block')
    .replace(/panel/g, 'board')
    .replace(/hero/g, 'intro')
    .replace(/sidebar/g, 'rail')
    .replace(/navbar/g, 'sign')
    .replace(/banner/g, 'billboard');
}

function mapToken(token) {
  if (EXACT[token]) return EXACT[token];
  for (const [from, to] of PREFIXES) {
    if (token.startsWith(from)) return clean(to + token.slice(from.length));
  }
  return clean('leaf-' + token);
}

const allTokens = new Set();
for (const file of files) {
  const text = fs.readFileSync(file, 'utf8');
  const start = text.indexOf('<template>');
  const end = text.lastIndexOf('</template>');
  if (start < 0 || end < 0) continue;
  const tpl = text.slice(start + 10, end);
  for (const m of tpl.matchAll(/\bclass="([^"]*)"/g)) {
    for (const token of m[1].split(/\s+/)) {
      if (!token || token.includes('{') || token.includes('}') || token.includes(':')) continue;
      allTokens.add(token);
    }
  }
}

const mapped = new Map();
const collisions = new Map();
for (const token of [...allTokens].sort()) {
  const next = mapToken(token);
  if (next === token) console.log('IDENTITY', token);
  mapped.set(token, next);
  if (collisions.has(next)) console.log('COLLISION', next, collisions.get(next), token);
  collisions.set(next, token);
}

fs.writeFileSync(path.resolve('.reskin/tools/token-map.json'), JSON.stringify(Object.fromEntries(mapped), null, 2));
console.log('tokens', mapped.size, 'unique new', new Set(mapped.values()).size);
const banned = /card|tile|panel|hero|sidebar|navbar|banner/i;
for (const [old, next] of mapped) if (banned.test(next)) console.log('BANNED', old, '->', next);
